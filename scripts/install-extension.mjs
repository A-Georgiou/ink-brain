// Installs or removes the Ink Brain session extension for Copilot CLI and the Copilot desktop app.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const EXTENSION_DIR = path.join(process.env.COPILOT_HOME || path.join(os.homedir(), ".copilot"), "extensions", "ink-brain");

export function installExtension() {
    const entry = pathToFileURL(path.join(root, "extension", "ink-brain.mjs")).href;
    const shim = [
        "// Generated by Ink Brain (npm run extension:install); loads the extension from your checkout.",
        'import { joinSession } from "@github/copilot-sdk/extension";',
        "",
        `const { start } = await import(${JSON.stringify(entry)});`,
        "await start({ joinSession });",
        "",
    ].join("\n");
    fs.mkdirSync(EXTENSION_DIR, { recursive: true });
    fs.writeFileSync(path.join(EXTENSION_DIR, "extension.mjs"), shim);
    return EXTENSION_DIR;
}

export function uninstallExtension() {
    fs.rmSync(EXTENSION_DIR, { recursive: true, force: true });
    return EXTENSION_DIR;
}

// Usage: node scripts/install-extension.mjs [--uninstall]
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    if (process.argv.includes("--uninstall")) {
        console.log(`Removed ${uninstallExtension()}`);
    } else {
        console.log(`Installed ${installExtension()}`);
        console.log("New Copilot CLI and desktop app sessions load it automatically; run /clear (or restart) in sessions that are already open.");
    }
}
